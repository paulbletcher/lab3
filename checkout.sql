-- Phase 2: Safe checkout and inventory audit trail
 -- Step 1: Configure automatic ID generation.
 BEGIN;

LOCK TABLE orders,
           order_items,
           inventory_log IN ACCESS EXCLUSIVE MODE;


ALTER TABLE orders
ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY;


ALTER TABLE order_items
ALTER COLUMN order_item_id ADD GENERATED BY DEFAULT AS IDENTITY;


ALTER TABLE inventory_log
ALTER COLUMN log_id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Initialize the order sequence above both existing
-- order IDs and historical order references.

SELECT setval(pg_get_serial_sequence('orders', 'order_id'), GREATEST(COALESCE(
                                                                                  (SELECT MAX(order_id)::bigint
                                                                                   FROM orders), 0), COALESCE(
                                                                                                                  (SELECT MAX(order_id)::bigint
                                                                                                                   FROM order_items), 0)) + 1, false) AS next_order_id;

-- Initialize the order item sequence above existing IDs.

SELECT setval(pg_get_serial_sequence('order_items', 'order_item_id'), COALESCE(
                                                                                   (SELECT MAX(order_item_id)::bigint
                                                                                    FROM order_items), 0) + 1, false) AS next_order_item_id;

-- Initialize the inventory log sequence above existing IDs.

SELECT setval(pg_get_serial_sequence('inventory_log', 'log_id'), COALESCE(
                                                                              (SELECT MAX(log_id)::bigint
                                                                               FROM inventory_log), 0) + 1, false) AS next_log_id;


COMMIT;